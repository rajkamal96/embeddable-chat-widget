import { existsSync, readdirSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

/** Regenerates src/generated/sites.ts from data/sites/<id>/{site.json,index.json}. */
export function registerSites(root = process.cwd()): string[] {
  const dir = join(root, 'data', 'sites');
  const ids = readdirSync(dir, { withFileTypes: true })
    .filter((d) => d.isDirectory())
    .map((d) => d.name)
    .sort();

  const ready: string[] = [];
  for (const id of ids) {
    const ok = existsSync(join(dir, id, 'site.json')) && existsSync(join(dir, id, 'index.json'));
    if (ok) ready.push(id);
    else console.warn(`Skipping "${id}": needs both site.json and index.json (run npm run ingest).`);
  }

  const v = (id: string) => id.replace(/-([a-z0-9])/g, (_, c: string) => c.toUpperCase()).replace(/^(\d)/, '_$1');
  const body = [
    '// AUTO-GENERATED by `npm run ingest` (or `npm run ingest -- --register`). Do not edit by hand.',
    "import { SiteConfigSchema, type SiteRegistry } from '../lib/sites';",
    "import type { SiteIndex } from '../lib/types';",
    ...ready.flatMap((id) => [
      `import ${v(id)}Config from '../../data/sites/${id}/site.json';`,
      `import ${v(id)}Index from '../../data/sites/${id}/index.json';`,
    ]),
    '',
    'export const SITES: SiteRegistry = {',
    ...ready.map(
      (id) => `  '${id}': { config: SiteConfigSchema.parse(${v(id)}Config), index: ${v(id)}Index as unknown as SiteIndex },`,
    ),
    '};',
    '',
  ].join('\n');
  writeFileSync(join(root, 'src', 'generated', 'sites.ts'), body);
  return ready;
}
